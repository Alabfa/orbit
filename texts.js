function copy(template, values = {}) {
  if (typeof template !== 'string') throw new TypeError('Unknown interface text');
  return template.replace(/\{(\w+)\}/g, (_, key) => {
    if (!Object.prototype.hasOwnProperty.call(values, key)) throw new Error('Missing text value: ' + key);
    return String(values[key]);
  });
}
